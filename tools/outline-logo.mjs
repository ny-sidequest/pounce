// One-off: turns the <text> in brand/pounce-logo.svg into outlined <path>s so the logo never depends on a web font.
// Needs the TTFs in tools/fonts/ (Audiowide, Exo 2 Bold: Google Fonts, OFL; not shipped) and `npm i -D opentype.js`.
// Usage: node tools/outline-logo.mjs  ->  assets/logo.svg
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import opentype from 'opentype.js';

const load = (p) => { const b = readFileSync(p); return opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength)); };
const audiowide = load('tools/fonts/Audiowide-Regular.ttf');
const exo = load('tools/fonts/Exo2-Bold.ttf');

function outline(font, text, { x, y, size, spacing }) {
  const scale = size / font.unitsPerEm;
  const glyphs = font.stringToGlyphs(text);
  const advances = glyphs.map((g, i) => g.advanceWidth * scale + (i < glyphs.length - 1 ? (font.getKerningValue(g, glyphs[i + 1]) || 0) * scale : 0) + spacing);
  const total = advances.reduce((a, b) => a + b, 0);
  let cx = x - total / 2;                       // text-anchor: middle (browsers include the trailing letter-spacing)
  let d = '';
  glyphs.forEach((g, i) => { d += g.getPath(cx, y, size).toPathData(2); cx += advances[i]; });
  return d;
}

let svg = readFileSync('brand/pounce-logo.svg', 'utf8');
const word = outline(audiowide, 'POUNCE', { x: 280, y: 236, size: 88, spacing: 2 });
const tag = outline(exo, 'LEAP BEFORE YOU LOOK', { x: 280, y: 276, size: 15, spacing: 7 });
svg = svg.replace(/<text id="wordmark"[^>]*>POUNCE<\/text>/, `<path id="wordmark" d="${word}" fill="#FF2E88" filter="url(#glow)"/>`);
svg = svg.replace(/<text id="tagline"[^>]*>LEAP BEFORE YOU LOOK<\/text>/, `<path id="tagline" d="${tag}" fill="#FFB238"/>`);
if (svg.includes('<text')) throw new Error('text left in logo');
mkdirSync('assets', { recursive: true });
writeFileSync('assets/logo.svg', svg);
writeFileSync('js/logo-paths.js', `// generated by tools/outline-logo.mjs (outlined Audiowide / Exo 2 Bold): the logo needs no web font\nexport const WORD_D = ${JSON.stringify(word)};\nexport const TAG_D = ${JSON.stringify(tag)};\n`);
console.log('wrote assets/logo.svg', svg.length, 'bytes');
